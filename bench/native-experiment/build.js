// Build the C text kernel to WebAssembly (experiment; not shipped — see docs/NATIVE.md).
//   npm i --no-save @yowasp/clang && node bench/native-experiment/build.js
//
// 1. Generates unicode_ranges.h from the JavaScript engine's own \p{L}\p{N}
//    classes, so the C word counter agrees exactly with src/core/text.js.
// 2. Compiles stet_text.c with Clang (the @yowasp/clang package: Clang itself
//    compiled to WebAssembly — no system compiler or per-platform build).
// 3. Writes stet_text.wasm next to this file.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { runClang } from '@yowasp/clang';

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, 'stet_text.wasm');

const re = /[\p{L}\p{N}]/u;
const ranges = [];
for (let cp = 128; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue;
  if (!re.test(String.fromCodePoint(cp))) continue;
  const last = ranges[ranges.length - 1];
  if (last && last[1] === cp - 1) last[1] = cp; else ranges.push([cp, cp]);
}
const ascii = Array.from({ length: 128 }, (_, c) => (re.test(String.fromCharCode(c)) ? 1 : 0));
const header = `/* Generated by native/build.js from the JS engine's \\p{L}\\p{N}. Do not edit. */
static const unsigned char ASCII_WORD[128] = {${ascii.join(',')}};
#define WORD_RANGE_COUNT ${ranges.length}
static const uint32_t WORD_RANGES[${ranges.length}][2] = {
${ranges.map(([a, b]) => `{0x${a.toString(16)},0x${b.toString(16)}}`).join(',\n')}
};
`;
fs.writeFileSync(path.join(here, 'unicode_ranges.h'), header);

const files = {
  'stet_text.c': fs.readFileSync(path.join(here, 'stet_text.c'), 'utf8'),
  'unicode_ranges.h': header,
};
const res = await runClang([
  'clang', '--target=wasm32', '-O3', '-nostdlib', '-ffreestanding', '-Wall', '-Werror',
  '-Wl,--no-entry', '-Wl,--export-dynamic', '-Wl,--strip-all', '-Wl,-z,stack-size=65536',
  'stet_text.c', '-o', 'stet_text.wasm',
], files);
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, res['stet_text.wasm']);
console.log(`unicode ranges: ${ranges.length}; wrote ${path.relative(process.cwd(), out)} (${res['stet_text.wasm'].length} bytes)`);
